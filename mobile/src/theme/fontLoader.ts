import { Platform } from 'react-native';

/**
 * Injects Google Font (Syne 700/800 & Inter) and global CSS variables
 * for Expo Web when running on localhost:8081 / browser.
 */
export function injectGlobalFonts() {
  if (Platform.OS !== 'web' || typeof document === 'undefined') return;

  const FONT_LINK_ID = 'syne-google-font-link';
  const FONT_STYLE_ID = 'syne-google-font-styles';

  if (!document.getElementById(FONT_LINK_ID)) {
    const preconnect1 = document.createElement('link');
    preconnect1.rel = 'preconnect';
    preconnect1.href = 'https://fonts.googleapis.com';
    document.head.appendChild(preconnect1);

    const preconnect2 = document.createElement('link');
    preconnect2.rel = 'preconnect';
    preconnect2.href = 'https://fonts.gstatic.com';
    preconnect2.crossOrigin = 'anonymous';
    document.head.appendChild(preconnect2);

    const fontLink = document.createElement('link');
    fontLink.id = FONT_LINK_ID;
    fontLink.rel = 'stylesheet';
    fontLink.href =
      'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Syne:wght@700;800&display=swap';
    document.head.appendChild(fontLink);
  }

  if (!document.getElementById(FONT_STYLE_ID)) {
    const style = document.createElement('style');
    style.id = FONT_STYLE_ID;
    style.innerHTML = `
      @import url('https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Syne:wght@700;800&display=swap');

      :root {
        --font-display: 'Syne', sans-serif;
        --font-sans: 'Inter', -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
      }

      /* Global base typography for Expo Web */
      html, body, #root {
        font-family: 'Inter', -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
      }

      /* Any bold / heading text generated by React Native Web automatically uses Syne */
      [style*="font-weight: 700"],
      [style*="font-weight: 800"],
      [style*="font-weight: 900"],
      [style*="font-weight: bold"],
      [style*="font-weight:bold"],
      [style*="font-weight:700"],
      [style*="font-weight:800"],
      [style*="font-weight:900"] {
        font-family: 'Syne', sans-serif !important;
      }

      /* Headings and explicit display font classes */
      h1, h2, h3, h4, h5, h6, .font-display, [data-font="display"] {
        font-family: 'Syne', sans-serif !important;
      }
    `;
    document.head.appendChild(style);
  }
}
